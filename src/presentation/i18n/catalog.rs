use super::Locale;
macro_rules! messages {
    ($($key:ident => ($en:literal, $fr:literal)),+ $(,)?) => {
        #[derive(Clone, Copy, Debug)]
        pub enum Text { $($key),+ }
        impl Text { pub const ALL: &'static [Self] = &[$(Self::$key),+]; }
        impl Locale {
            pub fn text(self, key: Text) -> &'static str {
                match (key, self == Self::FR) { $((Text::$key, false) => $en, (Text::$key, true) => $fr),+ }
            }
        }
    };
}
